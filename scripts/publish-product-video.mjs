import OSS from 'ali-oss';
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Credentials stay in the ignored local environment, never in public metadata.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
process.loadEnvFile(path.join(root, 'data/oss.env'));
const required = ['OSS_ACCESS_KEY_ID', 'OSS_ACCESS_KEY_SECRET', 'OSS_REGION', 'OSS_BUCKET'];
if (required.some((name) => !process.env[name])) throw new Error('OSS configuration is incomplete.');
const client = new OSS({
  region: process.env.OSS_REGION, bucket: process.env.OSS_BUCKET,
  accessKeyId: process.env.OSS_ACCESS_KEY_ID, accessKeySecret: process.env.OSS_ACCESS_KEY_SECRET,
  secure: true, authorizationV4: true, timeout: 180_000,
});
const base = path.join(root, 'videos/qingjian-launch/renders');
const files = [
  ['video', 'qingjian-launch-1080p.mp4', 'video/mp4'],
  ['poster', 'qingjian-launch-poster.jpg', 'image/jpeg'],
  ['project', 'qingjian-launch-editable.zip', 'application/zip'],
];
const assets = {};
for (const [kind, filename, mime] of files) {
  const file = path.join(base, filename);
  const bytes = await readFile(file);
  const sha256 = createHash('sha256').update(bytes).digest('hex');
  const prefix = (process.env.OSS_PREFIX || 'qingjian').replace(/^\/+|\/+$/g, '');
  const key = `${prefix}/marketing/launch/${sha256.slice(0, 16)}/${filename}`;
  const headers = {
    'Content-Type': mime, 'Cache-Control': 'public, max-age=31536000, immutable',
    'x-oss-object-acl': 'public-read', 'x-oss-meta-sha256': sha256,
    ...(kind === 'project' ? { 'Content-Disposition': `attachment; filename="${filename}"` } : {}),
  };
  if (bytes.length > 1024 * 1024) {
    await client.multipartUpload(key, file, { partSize: 1024 * 1024, parallel: 2, mime, headers });
  } else await client.put(key, file, { mime, headers });
  const url = `https://${process.env.OSS_BUCKET}.${process.env.OSS_REGION}.aliyuncs.com/${key}`;
  const response = await fetch(url, { method: 'HEAD' });
  if (!response.ok || Number(response.headers.get('content-length')) !== bytes.length) {
    throw new Error(`Anonymous object verification failed: ${filename} (${response.status})`);
  }
  assets[kind] = { url, bytes: bytes.length, sha256, contentType: mime };
  console.log(`Published and verified ${kind}: ${url}`);
}
const manifest = {
  title: '96 秒了解轻剪', durationSeconds: 96, width: 1920, height: 1080, fps: 30,
  publishedAt: new Date().toISOString(), assets,
};
await writeFile(path.join(root, 'public/product-video.json'), JSON.stringify(manifest, null, 2) + '\n');
await writeFile(path.join(root, 'src/productVideo.ts'),
  '// Public marketing assets. Generated by scripts/publish-product-video.mjs.\n' +
  `export const productVideo = ${JSON.stringify(manifest, null, 2)} as const;\n`);
